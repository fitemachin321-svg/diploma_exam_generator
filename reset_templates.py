# Создаём предмет (если нет)
subject, _ = Subject.objects.get_or_create(
    name="Математика",
    defaults={"description": "Основные математические темы", "created_by_id": 1}
)
print(f"Предмет: {subject.name}\n")

def create_topic(name, content, difficulty):
    topic, _ = Topic.objects.get_or_create(
        subject=subject,
        title=name,
        defaults={"content": content, "difficulty_level": difficulty}
    )
    print(f"Тема: {topic.title}")
    return topic

def add_open(topic, text, answer):
    QuestionTemplate.objects.create(
        topic=topic,
        question_type='open',
        text_template=text,
        correct_answer_template=answer,
        points=2
    )

def add_single(topic, text, correct, wrong):
    options = [
        {"text": str(correct), "is_correct": True},
        {"text": str(wrong), "is_correct": False}
    ]
    QuestionTemplate.objects.create(
        topic=topic,
        question_type='single',
        text_template=text,
        correct_answer_template=str(correct),
        options_template=options,
        points=2
    )

